volatile HardFaultContextTypeDef g_hardfault_context;
__attribute__((used)) static void HardFault_Capture(uint32_t *stacked) {
  g_hardfault_context.signature = 0x48464C54U;
  g_hardfault_context.ipsr = __get_IPSR();
  g_hardfault_context.control = __get_CONTROL();
  g_hardfault_context.msp = __get_MSP();
  g_hardfault_context.psp = __get_PSP();
  g_hardfault_context.r0 = stacked[0]; g_hardfault_context.r1 = stacked[1];
  g_hardfault_context.r2 = stacked[2]; g_hardfault_context.r3 = stacked[3];
  g_hardfault_context.r12 = stacked[4]; g_hardfault_context.lr = stacked[5];
  g_hardfault_context.pc = stacked[6]; g_hardfault_context.xpsr = stacked[7];
  g_hardfault_context.cfsr = SCB->CFSR; g_hardfault_context.hfsr = SCB->HFSR;
  g_hardfault_context.dfsr = SCB->DFSR; g_hardfault_context.afsr = SCB->AFSR;
  g_hardfault_context.bfar = SCB->BFAR; g_hardfault_context.mmfar = SCB->MMFAR;
}
static void HardFault_CaptureFromHandler(void) __attribute__((naked));
static void HardFault_CaptureFromHandler(void) {
  __asm volatile("tst lr, #4\n"
                 "ite eq\n"
                 "mrseq r0, msp\n"
                 "mrsne r0, psp\n"
                 "bl HardFault_Capture\n"
                 "b .\n");
}

